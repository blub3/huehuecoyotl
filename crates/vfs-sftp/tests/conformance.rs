//! SFTP against the rclone test server (tests/servers): listing, ranged and sequential reads,
//! wrong password, trust-on-first-use host key.
//! `COYOTL_TEST_SERVERS=1 cargo test --manifest-path crates/vfs-sftp/Cargo.toml`
use huehuecoyotl_vfs::{Protocol, RemoteConfig, RemoteSource, Source, VPath, VfsError};
use huehuecoyotl_vfs_sftp::SftpSource;

const MOVIE: &str = "/Movies/Alien (1979)/Alien.1979.1080p.mkv";

fn cfg() -> RemoteConfig {
    RemoteConfig {
        protocol: Protocol::Sftp,
        host: "172.29.0.12".into(),
        port: Some(2022),
        share: String::new(),
        user: "coyotl".into(),
        password: "coyotl-test".into(),
        tls: false,
        host_key: None,
        key_file: None,
    }
}

#[tokio::test(flavor = "multi_thread")]
async fn sftp_conformance() {
    if std::env::var_os("COYOTL_TEST_SERVERS").is_none() {
        return;
    }
    let reference = std::fs::read(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../tests/servers/fixtures/Movies/Alien (1979)/Alien.1979.1080p.mkv"
    ))
    .unwrap();
    let src = SftpSource::new(cfg());
    let mut names: Vec<_> = src
        .list(&VPath::new("/"))
        .await
        .unwrap()
        .into_iter()
        .map(|e| (e.name, e.is_dir))
        .collect();
    names.sort();
    assert_eq!(
        names,
        [
            ("Movies".to_string(), true),
            ("Shows".to_string(), true),
            ("notes.txt".to_string(), false)
        ]
    );
    assert_eq!(
        src.stat(&VPath::new(MOVIE)).await.unwrap().size,
        reference.len() as u64
    );
    let b = src
        .read_at(&VPath::new(MOVIE), 1_000_003, 65_536)
        .await
        .unwrap();
    assert!(b[..] == reference[1_000_003..1_000_003 + 65_536]);
    let mut got = Vec::new();
    loop {
        let b = src
            .read_at(&VPath::new(MOVIE), got.len() as u64, 256 * 1024)
            .await
            .unwrap();
        if b.is_empty() {
            break;
        }
        got.extend_from_slice(&b);
    }
    assert!(got == reference);
    assert!(matches!(
        src.list(&VPath::new("/Nope")).await,
        Err(VfsError::NotFound(_))
    ));

    // Trust on first use: the key seen is reported; a different expected key is refused.
    let key = src.host_key().expect("host key recorded");
    assert!(key.starts_with("SHA256:"), "{key}");
    let mut pinned = cfg();
    pinned.host_key = Some(key);
    assert!(SftpSource::new(pinned).list(&VPath::new("/")).await.is_ok());
    let mut wrong_key = cfg();
    wrong_key.host_key = Some("SHA256:not-the-key".into());
    assert!(
        SftpSource::new(wrong_key)
            .list(&VPath::new("/"))
            .await
            .is_err()
    );

    let mut bad = cfg();
    bad.password = "wrong".into();
    let e = SftpSource::new(bad)
        .list(&VPath::new("/"))
        .await
        .unwrap_err();
    assert!(matches!(e, VfsError::Auth(_)), "{e:?}");

    // A changed host key is refused with a message that says so.
    let mut changed = cfg();
    changed.host_key = Some("SHA256:not-the-key".into());
    let e = SftpSource::new(changed)
        .list(&VPath::new("/"))
        .await
        .unwrap_err();
    assert!(
        matches!(&e, VfsError::Auth(m) if m.contains("host key changed")),
        "{e:?}"
    );
}

/// Key files generated by tests/servers/up.sh.
fn key(name: &str) -> String {
    format!(
        "{}/../../tests/servers/keys/{name}",
        env!("CARGO_MANIFEST_DIR")
    )
}

#[tokio::test(flavor = "multi_thread")]
async fn sftp_key_login() {
    if std::env::var_os("COYOTL_TEST_SERVERS").is_none() {
        return;
    }
    let with_key = |file: &str, passphrase: &str| {
        let mut c = cfg();
        c.key_file = Some(key(file));
        c.password = passphrase.into();
        SftpSource::new(c)
    };
    let root = VPath::new("/");
    // A key without a passphrase, and one with its passphrase.
    assert!(with_key("id_ed25519", "").list(&root).await.is_ok());
    assert!(
        with_key("id_ed25519_pass", "coyotl-key")
            .list(&root)
            .await
            .is_ok()
    );
    // A missing or wrong passphrase, and a missing file, fail with a clear error.
    for (file, pass, want) in [
        ("id_ed25519_pass", "", "needs its passphrase"),
        ("id_ed25519_pass", "wrong", "wrong passphrase"),
        ("no-such-key", "", "cannot be read"),
    ] {
        let e = with_key(file, pass).list(&root).await.unwrap_err();
        assert!(e.to_string().contains(want), "{file}/{pass}: {e}");
        assert!(
            !e.to_string().contains("coyotl-key"),
            "passphrase leaked: {e}"
        );
    }
}

async fn chunks(parts: Vec<huehuecoyotl_vfs::Result<bytes::Bytes>>) -> huehuecoyotl_vfs::Chunks {
    let (tx, rx) = tokio::sync::mpsc::channel(parts.len().max(1));
    for p in parts {
        tx.send(p).await.unwrap();
    }
    rx
}

async fn read_all(src: &SftpSource, p: &VPath) -> Vec<u8> {
    let mut out = Vec::new();
    loop {
        let b = src.read_at(p, out.len() as u64, 1 << 20).await.unwrap();
        if b.is_empty() {
            return out;
        }
        out.extend_from_slice(&b);
    }
}

/// Issue #151: writing, on the writable server next to the read-only one.
#[tokio::test(flavor = "multi_thread")]
async fn sftp_writes() {
    if std::env::var_os("COYOTL_TEST_SERVERS").is_none() {
        return;
    }
    use bytes::Bytes;
    use huehuecoyotl_vfs::{Expected, safe_write};
    let mut c = cfg();
    c.port = Some(2023);
    let src = SftpSource::new(c);
    let dir = VPath::new(format!("/t-sftp-{}", std::process::id()));
    src.create_dir(&dir).await.unwrap();
    let file = dir.join("Tëst file.bin");
    let body: Vec<u8> = (0..1_500_000u32).map(|i| (i % 251) as u8).collect();
    let parts = body
        .chunks(400_000)
        .map(|p| Ok(Bytes::copy_from_slice(p)))
        .collect();
    assert_eq!(
        safe_write(&src, &file, chunks(parts).await, None)
            .await
            .unwrap(),
        body.len() as u64
    );
    assert!(read_all(&src, &file).await == body);
    let st = src.stat(&file).await.unwrap();
    let x = Expected {
        size: st.size,
        mtime: st.mtime,
    };
    let broken = chunks(vec![
        Ok(Bytes::from_static(b"half")),
        Err(VfsError::Unreachable("cut".into())),
    ])
    .await;
    assert!(safe_write(&src, &file, broken, Some(x)).await.is_err());
    assert!(read_all(&src, &file).await == body, "old file kept");
    let stale = Expected {
        size: x.size + 1,
        ..x
    };
    let e = safe_write(
        &src,
        &file,
        chunks(vec![Ok(Bytes::from_static(b"x"))]).await,
        Some(stale),
    )
    .await
    .unwrap_err();
    assert!(matches!(e, VfsError::Changed(_)), "{e:?}");
    // Plain SFTP may refuse to rename over a file: replacing still works.
    safe_write(
        &src,
        &file,
        chunks(vec![Ok(Bytes::from_static(b"new"))]).await,
        Some(x),
    )
    .await
    .unwrap();
    assert_eq!(read_all(&src, &file).await, b"new");
    let moved = dir.join("moved.bin");
    src.rename(&file, &moved).await.unwrap();
    huehuecoyotl_vfs::write::check_writable(&src, &dir)
        .await
        .unwrap();
    assert_eq!(src.list(&dir).await.unwrap().len(), 1);
    src.remove(&moved).await.unwrap();
    src.remove_dir(&dir).await.unwrap();

    let ro = SftpSource::new(cfg());
    let e = huehuecoyotl_vfs::write::check_writable(&ro, &VPath::new("/"))
        .await
        .unwrap_err();
    assert!(
        matches!(e, VfsError::ReadOnly(_)),
        "read-only server gave {e:?}"
    );
}
