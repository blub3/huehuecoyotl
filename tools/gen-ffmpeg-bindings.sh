#!/usr/bin/env bash
# Regenerates the FFmpeg types the media probe reads. Only types and constants: the functions
# are loaded at runtime (crates/probe/src/ffi.rs), so nothing links against FFmpeg at build
# time. Run after an FFmpeg major version change.
#
#   gen-ffmpeg-bindings.sh                    ffi_types.rs from the libmpv bundle (FFmpeg 8.1)
#   gen-ffmpeg-bindings.sh INCLUDE OUT LABEL  e.g. the Flatpak SDK's headers into
#                                             crates/probe/src/ffi_types_71.rs, label 7.1
#
# Needs bindgen-cli 0.73 and libclang (LIBCLANG_PATH pointing at its folder).
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)
inc="${1:-$root/third_party/mpv/out/include}"
out="${2:-$root/crates/probe/src/ffi_types.rs}"
label="${3:-8.1}"
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
# A libclang without its resource folder (e.g. the PyPI wheel) needs the compiler's own headers
# (stddef.h, stdarg.h); GCC's work.
builtin=$(gcc -print-file-name=include 2>/dev/null || true)
cat > "$tmp/wrapper.h" <<'H'
#include <libavformat/avformat.h>
#include <libavcodec/avcodec.h>
#include <libavutil/channel_layout.h>
#include <libavutil/dovi_meta.h>
#include <libavutil/pixdesc.h>
H
{
  echo "// Generated by tools/gen-ffmpeg-bindings.sh from the FFmpeg $label headers. Do not edit."
  echo "#![allow(non_camel_case_types, non_snake_case, non_upper_case_globals, dead_code, clippy::all)]"
  bindgen "$tmp/wrapper.h" \
    --no-doc-comments --use-core --default-enum-style consts \
    --opaque-type AVIOContext --allowlist-type 'AVFormatContext|AVInputFormat|AVStream|AVCodecParameters|AVIOContext|AVDictionaryEntry|AVChapter|AVRational|AVPacketSideData|AVDOVIDecoderConfigurationRecord|AVChannelLayout|AVPixFmtDescriptor|AVComponentDescriptor' \
    --allowlist-type 'AVMediaType|AVCodecID|AVColorTransferCharacteristic|AVColorPrimaries|AVFieldOrder|AVPacketSideDataType|AVFrame|AVCodecContext|AVSampleFormat' \
    --allowlist-var 'AV_DISPOSITION_.*|AVSEEK_SIZE|AVFMT_FLAG_CUSTOM_IO|AV_PROFILE_.*|AV_DICT_.*|AV_PIX_FMT_FLAG_.*|LIBAVFORMAT_VERSION_MAJOR|LIBAVCODEC_VERSION_MAJOR|LIBAVUTIL_VERSION_MAJOR' \
    -- -I"$inc" ${builtin:+-I"$builtin"}
} > "$out"
echo "wrote $out ($(wc -l < "$out") lines)"
